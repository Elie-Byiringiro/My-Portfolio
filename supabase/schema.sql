-- =============================================================
-- Security: allow public read, keep write locked down
-- =============================================================

alter table public.profile enable row level security;
alter table public.stats enable row level security;
alter table public.focus enable row level security;
alter table public.experience enable row level security;
alter table public.skills enable row level security;
alter table public.projects enable row level security;
alter table public.posts enable row level security;

do $$
declare t text;
begin
  foreach t in array array['profile', 'stats', 'focus', 'experience', 'testimonials', 'skills', 'projects', 'posts'] loop
    execute format('drop policy if exists "public read %s" on public.%I;', t, t);
    execute format('create policy "public read %s" on public.%I for select using (true);', t, t);
  end loop;
end $$;