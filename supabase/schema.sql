-- =============================================================
-- Portfolio schema for Supabase
-- Run this in the Supabase SQL editor (Dashboard > SQL > New query)
-- It creates the tables, seeds them with the current content and
-- enables public read access for the anon key.
-- =============================================================

create extension if not exists "pgcrypto";
create extension if not exists "vector";

-- ---------------- profile (singleton row) ----------------
create table if not exists public.profile (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  alias text,
  status text,
  location text,
  started_coding text,
  focus text,
  email text,
  whatsapp text,
  instagram text,
  github text,
  roles text[] default '{}'::text[]
);

-- ---------------- stats ----------------
create table if not exists public.stats (
  id bigint generated by default as identity primary key,
  label text not null,
  value integer not null,
  suffix text default '',
  color text default 'green',
  sort_order integer default 0
);

-- ---------------- focus ----------------
create table if not exists public.focus (
  id bigint generated by default as identity primary key,
  num text not null,
  title text not null,
  text text not null,
  sort_order integer default 0
);

-- ---------------- experience ----------------
create table if not exists public.experience (
  id bigint generated by default as identity primary key,
  period text not null,
  role text not null,
  place text,
  type text,
  text text not null,
  tags text[] default '{}'::text[],
  sort_order integer default 0
);

-- ---------------- testimonials ----------------
create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  quote text not null,
  name text not null,
  role text,
  rating integer default 5,
  sort_order integer default 0
);

-- ---------------- skills ----------------
create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  category text not null,
  skill text not null,
  level text default 'intermediate',
  percent integer default 70,
  sort_order integer default 0
);

-- ---------------- projects ----------------
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null,
  preview text default '',
  tags text[] default '{}'::text[],
  source_url text,
  live_url text,
  sort_order integer default 0
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  excerpt text not null,
  body text not null,
  category text default 'article',
  tags text[] default '{}'::text[],
  published_at date default current_date,
  sort_order integer default 0
);

